-- Run in the Supabase SQL editor (optional: Hibernate can create this with ddl-auto=update).
CREATE TABLE IF NOT EXISTS short_urls (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_code   VARCHAR(32)   NOT NULL,
    original_url VARCHAR(2048) NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ,
    click_count  BIGINT        NOT NULL DEFAULT 0,
    custom_alias BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_short_urls_short_code UNIQUE (short_code)
);

CREATE INDEX IF NOT EXISTS idx_short_urls_expires_at ON short_urls (expires_at) WHERE expires_at IS NOT NULL;

-- Supabase exposes public tables through PostgREST; this app connects directly over JDBC,
-- so lock the table down from the public API:
ALTER TABLE short_urls ENABLE ROW LEVEL SECURITY;
